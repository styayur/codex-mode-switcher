#requires -Version 7.4
<#
.SYNOPSIS
Install, update, verify or uninstall the Codex Mode Switcher program files.
.DESCRIPTION
The installer owns only its standalone tool directory and explicitly recorded legacy
entry-point shims. It never rewrites Codex configuration, authentication, sessions or
user backups under CODEX_HOME.
#>
[CmdletBinding(SupportsShouldProcess, ConfirmImpact = 'Medium')]
[Diagnostics.CodeAnalysis.SuppressMessageAttribute('PSReviewUnusedParameter', '', Justification = 'Parameters are consumed by the installer action functions.')]
param(
    [ValidateSet('Install', 'Update', 'Verify', 'Uninstall')]
    [string]$Action = 'Install',
    [string]$InstallDirectory,
    [string]$CodexHome,
    [string]$SourceDirectory,
    [switch]$DryRun,
    [switch]$Force,
    [switch]$NoLegacyEntry,
    [switch]$CreateLegacyEntry,
    [switch]$Json,
    [switch]$PassThru
)
Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
$script:ShouldProcessApproved = $true
if ($Action -in @('Install', 'Update', 'Uninstall')) {
    $script:ShouldProcessApproved = $PSCmdlet.ShouldProcess("Codex Mode Switcher $Action", $Action)
}
. (Join-Path $PSScriptRoot 'Payload.ps1')

$script:LegacyMarker = 'Generated by Codex Mode Switcher installer'
$script:Warnings = [Collections.Generic.List[string]]::new()

function Resolve-FullDirectoryPath {
    param([Parameter(Mandatory)][string]$Path, [string]$Description = 'Path')
    if ([string]::IsNullOrWhiteSpace($Path) -or -not [IO.Path]::IsPathFullyQualified($Path)) {
        throw "$Description must be an absolute filesystem path."
    }
    $full = [IO.Path]::GetFullPath($Path)
    $trimmed = $full.TrimEnd([IO.Path]::DirectorySeparatorChar, [IO.Path]::AltDirectorySeparatorChar)
    $root = [IO.Path]::GetPathRoot($full).TrimEnd([IO.Path]::DirectorySeparatorChar, [IO.Path]::AltDirectorySeparatorChar)
    if ([string]::IsNullOrWhiteSpace($trimmed) -or $trimmed -eq $root) {
        throw "$Description cannot be a filesystem root."
    }
    return $trimmed
}

function Resolve-CodexHome {
    param([string]$Path)
    $value = if (-not [string]::IsNullOrWhiteSpace($Path)) { $Path }
        elseif (-not [string]::IsNullOrWhiteSpace($env:CODEX_HOME)) { $env:CODEX_HOME }
        else { Join-Path $HOME '.codex' }
    return Resolve-FullDirectoryPath -Path $value -Description 'Codex home'
}

function Resolve-InstallDirectory {
    param([string]$Path)
    if (-not [string]::IsNullOrWhiteSpace($Path)) {
        return Resolve-FullDirectoryPath -Path $Path -Description 'Install directory'
    }
    $local = [Environment]::GetFolderPath('LocalApplicationData')
    if ([string]::IsNullOrWhiteSpace($local)) { $local = Join-Path $HOME '.local/share' }
    return Resolve-FullDirectoryPath -Path (Join-Path $local 'Programs/CodexModeSwitcher') -Description 'Install directory'
}

function Get-InstallerStateDirectory {
    $local = [Environment]::GetFolderPath('LocalApplicationData')
    if ([string]::IsNullOrWhiteSpace($local)) { $local = Join-Path $HOME '.local/share' }
    return [IO.Path]::GetFullPath((Join-Path $local 'CodexModeSwitcher/installer'))
}

function Test-PathWithin {
    param([Parameter(Mandatory)][string]$Child, [Parameter(Mandatory)][string]$Parent)
    $childFull = [IO.Path]::GetFullPath($Child).TrimEnd([IO.Path]::DirectorySeparatorChar, [IO.Path]::AltDirectorySeparatorChar)
    $parentFull = [IO.Path]::GetFullPath($Parent).TrimEnd([IO.Path]::DirectorySeparatorChar, [IO.Path]::AltDirectorySeparatorChar)
    if ($childFull.Equals($parentFull, [StringComparison]::OrdinalIgnoreCase)) { return $true }
    return $childFull.StartsWith($parentFull + [IO.Path]::DirectorySeparatorChar, [StringComparison]::OrdinalIgnoreCase)
}

function Assert-TargetSafety {
    param(
        [Parameter(Mandatory)][string]$Target,
        [Parameter(Mandatory)][string]$HomePath,
        [Parameter(Mandatory)][string]$Source,
        [ValidateSet('Install', 'Update', 'Verify', 'Uninstall')][string]$Action
    )
    if ($Target.Equals($HomePath, [StringComparison]::OrdinalIgnoreCase)) {
        throw 'The install directory must be separate from CODEX_HOME.'
    }
    if ((Test-PathWithin -Child $HomePath -Parent $Target) -or (Test-PathWithin -Child $Target -Parent $HomePath)) {
        throw 'The install directory and CODEX_HOME must not contain one another.'
    }
    if ($Action -in @('Install', 'Update') -and -not $Target.Equals($Source, [StringComparison]::OrdinalIgnoreCase) -and (Test-PathWithin -Child $Target -Parent $Source)) {
        throw 'The install directory must be outside the extracted source directory.'
    }
    if ($Action -eq 'Uninstall' -and -not $Target.Equals($Source, [StringComparison]::OrdinalIgnoreCase) -and (Test-PathWithin -Child $Target -Parent $Source)) {
        throw 'Refusing to uninstall a directory that contains the running source tree.'
    }
    if (Test-Path -LiteralPath $Target) {
        $item = Get-Item -LiteralPath $Target -Force
        if (($item.Attributes -band [IO.FileAttributes]::ReparsePoint) -ne 0) {
            throw "Refusing to operate on a reparse point: $Target"
        }
        if (-not $item.PSIsContainer) { throw "Install directory is a file: $Target" }
    }
}

function Get-InstallReceipt {
    param([Parameter(Mandatory)][string]$Target)
    $path = Join-Path $Target 'install.json'
    if (-not [IO.File]::Exists($path)) { return $null }
    try { $receipt = Get-Content -LiteralPath $path -Raw | ConvertFrom-Json -AsHashtable -ErrorAction Stop }
    catch { throw "Installation receipt is unreadable: $path" }
    if ($receipt.owner -cne $script:CodexModeOwner -or $receipt.schema_version -ne 1) {
        throw "Installation receipt is not owned by Codex Mode Switcher: $path"
    }
    return $receipt
}

function Write-JsonFile {
    param([Parameter(Mandatory)][string]$Path, [Parameter(Mandatory)]$Value)
    $directory = Split-Path -Path $Path -Parent
    [void][IO.Directory]::CreateDirectory($directory)
    $bytes = [Text.UTF8Encoding]::new($false).GetBytes(($Value | ConvertTo-Json -Depth 12))
    $temporary = "$Path.$([guid]::NewGuid().ToString('N')).tmp"
    [IO.File]::WriteAllBytes($temporary, $bytes)
    try {
        if ([IO.File]::Exists($Path)) { [IO.File]::Move($temporary, $Path, $true) }
        else { [IO.File]::Move($temporary, $Path) }
    } finally {
        if ([IO.File]::Exists($temporary)) { [IO.File]::Delete($temporary) }
    }
}

function ConvertTo-QuotedPowerShellLiteral {
    param([Parameter(Mandatory)][string]$Value)
    return $Value.Replace("'", "''")
}

function Invoke-ModuleImportCheck {
    param([Parameter(Mandatory)][string]$Target)
    $pwsh = (Get-Command pwsh -ErrorAction SilentlyContinue).Source
    if ([string]::IsNullOrWhiteSpace($pwsh)) {
        $candidate = Join-Path $PSHOME 'pwsh.exe'
        if (-not [IO.File]::Exists($candidate)) { $candidate = Join-Path $PSHOME 'pwsh' }
        if (-not [IO.File]::Exists($candidate)) { throw 'PowerShell 7 executable was not found for installation verification.' }
        $pwsh = $candidate
    }
    $manifest = Join-Path $Target 'CodexModeSwitcher.psd1'
    $entry = Join-Path $Target 'codex-mode.ps1'
    $check = @"
`$ErrorActionPreference = 'Stop'
Import-Module '$(ConvertTo-QuotedPowerShellLiteral $manifest)' -Force -ErrorAction Stop
`$command = Get-Command Invoke-CodexCommand -Module CodexModeSwitcher -ErrorAction Stop
if (-not `$command) { throw 'Invoke-CodexCommand was not exported.' }
if (-not (Test-Path -LiteralPath '$(ConvertTo-QuotedPowerShellLiteral $entry)' -PathType Leaf)) { throw 'Installed entry script is missing.' }
"@
    $null = & $pwsh -NoLogo -NoProfile -NonInteractive -Command $check 2>&1
    if ($LASTEXITCODE -ne 0) {
        throw 'Installed module verification failed. The installation is incomplete or corrupt; reinstall from the complete release archive.'
    }
}

function Copy-Payload {
    param([Parameter(Mandatory)][string]$Source, [Parameter(Mandatory)][string]$Target)
    $copied = [Collections.Generic.List[string]]::new()
    foreach ($relative in @(Get-CodexModePayloadFile -Root $Source)) {
        if ([IO.Path]::IsPathRooted($relative) -or $relative -match '(^|[\\/])\.\.([\\/]|$)') {
            throw "Refusing unsafe payload path: $relative"
        }
        $sourcePath = Join-Path $Source $relative
        $targetPath = Join-Path $Target $relative
        [void][IO.Directory]::CreateDirectory((Split-Path -Path $targetPath -Parent))
        [IO.File]::Copy($sourcePath, $targetPath, $false)
        $copied.Add($relative)
    }
    return @($copied)
}

function Format-InstallReceipt {
    param(
        [Parameter(Mandatory)][string]$Target,
        [Parameter(Mandatory)][string]$Source,
        [Parameter(Mandatory)][string]$Version
    )
    $files = foreach ($relative in @(Get-CodexModePayloadFile -Root $Target)) {
        $path = Join-Path $Target $relative
        [ordered]@{
            path = $relative
            sha256 = Get-CodexModeFileHash -Path $path
            size = ([IO.FileInfo]::new($path)).Length
        }
    }
    return [ordered]@{
        schema_version = 1
        owner = $script:CodexModeOwner
        product = $script:CodexModeProduct
        version = $Version
        installed_at = [DateTime]::UtcNow.ToString('o')
        source = $Source
        install_directory = $Target
        entry = 'codex-mode.ps1'
        module = 'src/CodexMode.psm1'
        files = @($files)
        shims = @()
    }
}

function Get-InstalledFileHealth {
    param([Parameter(Mandatory)][string]$Target, [Parameter(Mandatory)]$Receipt)
    $missing = [Collections.Generic.List[string]]::new()
    $modified = [Collections.Generic.List[string]]::new()
    $known = [Collections.Generic.HashSet[string]]::new([StringComparer]::OrdinalIgnoreCase)
    foreach ($entry in @($Receipt.files)) {
        $relative = [string]$entry.path
        if ([string]::IsNullOrWhiteSpace($relative) -or [IO.Path]::IsPathRooted($relative) -or
            $relative -match '(^|[\\/])\.\.([\\/]|$)') {
            $modified.Add("$relative (unsafe path)")
            continue
        }
        [void]$known.Add($relative)
        $path = Join-Path $Target $relative
        if (-not [IO.File]::Exists($path)) { $missing.Add($relative); continue }
        if ((Get-CodexModeFileHash -Path $path) -cne [string]$entry.sha256) { $modified.Add($relative) }
    }
    foreach ($relative in $script:CodexModeRequiredFiles + @('src/CodexMode.psm1')) {
        if (-not $known.Contains($relative)) { $missing.Add($relative) }
    }
    $healthy = $missing.Count -eq 0 -and $modified.Count -eq 0
    [pscustomobject]@{
        Healthy = $healthy
        Missing = @($missing)
        Modified = @($modified)
    }
}

function Get-RepairCommand {
    param([Parameter(Mandatory)][string]$Target)
    return "Download the complete CodexModeSwitcher-*.zip release archive, extract it, then run: pwsh -NoProfile -File .\CodexModeSwitcher\install.ps1 -Action Install -Force -InstallDirectory `"$Target`""
}

function Get-LegacyEntryContent {
    param([Parameter(Mandatory)][string]$TargetEntry, [ValidateSet('PowerShell', 'Cmd')][string]$Kind)
    if ($Kind -eq 'PowerShell') {
        $entry = ConvertTo-QuotedPowerShellLiteral $TargetEntry
        $installer = ConvertTo-QuotedPowerShellLiteral (Join-Path (Split-Path -Path $TargetEntry -Parent) 'install.ps1')
        return @"
#requires -Version 7.4
# $($script:LegacyMarker). Do not edit.
`$ErrorActionPreference = 'Stop'
`$entry = '$entry'
if (-not (Test-Path -LiteralPath `$entry -PathType Leaf)) {
    [Console]::Error.WriteLine("Codex Mode Switcher is incomplete: `$entry is missing.")
    [Console]::Error.WriteLine("Reinstall the complete release archive with: pwsh -NoProfile -File '$installer' -Action Install -Force")
    exit 2
}
& `$entry @args
exit `$LASTEXITCODE
"@
    }
    $cmdEntry = $TargetEntry.Replace('%', '%%')
    return @"
@echo off
rem $($script:LegacyMarker). Do not edit.
pwsh.exe -NoLogo -NoProfile -File "$cmdEntry" %*
exit /b %errorlevel%
"@
}

function Write-LegacyEntry {
    param(
        [Parameter(Mandatory)][string]$Path,
        [Parameter(Mandatory)][string]$Content,
        [switch]$DryRun
    )
    if ($DryRun) { return }
    $bytes = [Text.UTF8Encoding]::new($false).GetBytes($Content)
    $temporary = "$Path.$([guid]::NewGuid().ToString('N')).tmp"
    try {
        [IO.File]::WriteAllBytes($temporary, $bytes)
        if ([IO.File]::Exists($Path)) { [IO.File]::Move($temporary, $Path, $true) }
        else { [IO.File]::Move($temporary, $Path) }
    } finally {
        if ([IO.File]::Exists($temporary)) { [IO.File]::Delete($temporary) }
    }
}

function Install-LegacyEntry {
    param(
        [Parameter(Mandatory)][string]$Target,
        [Parameter(Mandatory)][string]$HomePath,
        [object[]]$ExistingShims = @(),
        [switch]$DryRun
    )
    $records = [Collections.Generic.List[object]]::new()
    $entries = @(
        [pscustomobject]@{ Kind = 'PowerShell'; Path = (Join-Path $HomePath 'codex-mode.ps1'); Target = (Join-Path $Target 'codex-mode.ps1') }
        [pscustomobject]@{ Kind = 'Cmd'; Path = (Join-Path $HomePath 'codex-mode.cmd'); Target = (Join-Path $Target 'codex-mode.cmd') }
    )
    foreach ($entry in $entries) {
        $existingRecord = @($ExistingShims | Where-Object { $_ -and $_.path -eq $entry.Path } | Select-Object -First 1)
        $record = if ($existingRecord.Count) { $existingRecord[0] } else { $null }
        $exists = [IO.File]::Exists($entry.Path)
        if ($NoLegacyEntry) {
            if ($record) { $records.Add($record) }
            continue
        }
        if (-not $exists -and -not $CreateLegacyEntry) {
            if ($record) { $records.Add($record) }
            continue
        }
        if ($exists) {
            $item = Get-Item -LiteralPath $entry.Path -Force
            if (($item.Attributes -band [IO.FileAttributes]::ReparsePoint) -ne 0) {
                $script:Warnings.Add("Skipped reparse-point legacy entry: $($entry.Path)")
                continue
            }
            $text = [IO.File]::ReadAllText($entry.Path)
            $alreadyShim = $text.Contains($script:LegacyMarker)
            if ($alreadyShim) {
                if ($entry.Kind -eq 'PowerShell' -and -not $text.Contains($entry.Target)) {
                    $alreadyShim = $false
                }
                if ($entry.Kind -eq 'Cmd' -and -not $text.Contains((Split-Path -Path $entry.Target -Parent))) {
                    $alreadyShim = $false
                }
            }
            if ($alreadyShim) {
                if ($record) { $records.Add($record) }
                continue
            }
        }
        $backupPath = $null
        $originalHash = $null
        $originalExists = $exists
        if ($exists) {
            if ($record -and $record.backup_path -and [IO.File]::Exists([string]$record.backup_path)) {
                $backupPath = [string]$record.backup_path
                $originalHash = [string]$record.original_sha256
            } else {
                $originalHash = Get-CodexModeFileHash -Path $entry.Path
                $backupDirectory = Join-Path (Get-InstallerStateDirectory) ('legacy-backups/' + [DateTime]::UtcNow.ToString('yyyyMMddTHHmmssfff') + '-' + [guid]::NewGuid().ToString('N').Substring(0, 8))
                if (-not $DryRun) { [void][IO.Directory]::CreateDirectory($backupDirectory) }
                $backupPath = Join-Path $backupDirectory ([IO.Path]::GetFileName($entry.Path))
                if (-not $DryRun) {
                    [IO.File]::Copy($entry.Path, $backupPath, $false)
                    Write-JsonFile -Path (Join-Path $backupDirectory 'backup.json') -Value ([ordered]@{
                        schema_version = 1
                        owner = $script:CodexModeOwner
                        original_path = $entry.Path
                        original_sha256 = $originalHash
                        created_at = [DateTime]::UtcNow.ToString('o')
                    })
                }
            }
        }
        $content = Get-LegacyEntryContent -TargetEntry $entry.Target -Kind $entry.Kind
        $bytes = [Text.UTF8Encoding]::new($false).GetBytes($content)
        $stream = [IO.MemoryStream]::new($bytes)
        try { $shimHash = (Get-FileHash -InputStream $stream -Algorithm SHA256).Hash.ToLowerInvariant() }
        finally { $stream.Dispose() }
        if (-not $DryRun) {
            try { Write-LegacyEntry -Path $entry.Path -Content $content }
            catch {
                $script:Warnings.Add("Could not update legacy entry path=[$($entry.Path)] target=[$($entry.Target)] kind=[$($entry.Kind)]: $($_.Exception.Message)")
                continue
            }
        }
        $records.Add([ordered]@{
            kind = $entry.Kind.ToLowerInvariant()
            path = $entry.Path
            target = $entry.Target
            sha256 = $shimHash
            original_exists = $originalExists
            original_sha256 = $originalHash
            backup_path = $backupPath
        })
    }
    return @($records)
}

function Restore-LegacyEntry {
    param([object[]]$Shims = @())
    $restored = [Collections.Generic.List[string]]::new()
    $removed = [Collections.Generic.List[string]]::new()
    foreach ($record in @($Shims)) {
        if (-not $record -or -not $record.path) { continue }
        $path = [string]$record.path
        if (-not [IO.File]::Exists($path)) { continue }
        $currentHash = Get-CodexModeFileHash -Path $path
        if ($currentHash -cne [string]$record.sha256) {
            $script:Warnings.Add("Preserved modified legacy entry: $path")
            continue
        }
        if ($record.original_exists -and $record.backup_path -and [IO.File]::Exists([string]$record.backup_path)) {
            $backupHash = Get-CodexModeFileHash -Path ([string]$record.backup_path)
            if ($backupHash -ceq [string]$record.original_sha256) {
                [IO.File]::Copy([string]$record.backup_path, $path, $true)
                $restored.Add($path)
                continue
            }
        }
        [IO.File]::Delete($path)
        $removed.Add($path)
    }
    [pscustomobject]@{ Restored = @($restored); Removed = @($removed) }
}

function ConvertTo-InstallerResult {
    param(
        [Parameter(Mandatory)][string]$State,
        [Parameter(Mandatory)][string]$Message,
        [string]$Code = $State,
        [string]$Version,
        [string]$Target,
        [string]$HomePath,
        [object[]]$Files = @(),
        [object[]]$Shims = @(),
        [string]$RepairCommand,
        [string[]]$Warnings = @(),
        [string]$LeftoverPath
    )
    [pscustomobject]@{
        State = $State
        Code = $Code
        Message = $Message
        Action = $Action
        Version = $Version
        InstallDirectory = $Target
        CodexHome = $HomePath
        FileCount = @($Files).Count
        Files = @($Files)
        Shims = @($Shims)
        RepairCommand = $RepairCommand
        Warnings = @($Warnings)
        LeftoverPath = $LeftoverPath
    }
}

function Write-InstallerResult {
    param([Parameter(Mandatory)]$Result)
    if ($Json) { $Result | ConvertTo-Json -Depth 12; return }
    if ($PassThru) { $Result; return }
    Write-Host "$($Result.State): $($Result.Message)"
    if ($Result.Version) { Write-Host "Version          : $($Result.Version)" }
    if ($Result.InstallDirectory) { Write-Host "Install directory: $($Result.InstallDirectory)" }
    if ($Result.CodexHome) { Write-Host "Codex home       : $($Result.CodexHome)" }
    if ($Result.FileCount) { Write-Host "Program files    : $($Result.FileCount)" }
    foreach ($shim in @($Result.Shims)) {
        if ($shim.path) { Write-Host "Entry shim       : $($shim.path)" }
    }
    foreach ($warning in @($Result.Warnings)) { Write-Warning $warning }
    if ($Result.RepairCommand) { Write-Host "Repair           : $($Result.RepairCommand)" }
    if ($Result.LeftoverPath) { Write-Host "Leftover path    : $($Result.LeftoverPath)" }
}

function Invoke-InstallAction {
    param([switch]$Update)
    $source = if (-not [string]::IsNullOrWhiteSpace($SourceDirectory)) {
        Resolve-FullDirectoryPath -Path $SourceDirectory -Description 'Source directory'
    } else {
        Resolve-FullDirectoryPath -Path (Split-Path -Path $PSScriptRoot -Parent) -Description 'Source directory'
    }
    $target = Resolve-InstallDirectory -Path $InstallDirectory
    $homePath = Resolve-CodexHome -Path $CodexHome
    Assert-TargetSafety -Target $target -HomePath $homePath -Source $source -Action $Action

    $payload = Assert-CodexModePayload -Root $source
    $sourceVersion = [string]$payload.Version
    $installedReceipt = if ([IO.Directory]::Exists($target)) { Get-InstallReceipt -Target $target } else { $null }

    if ($source.Equals($target, [StringComparison]::OrdinalIgnoreCase)) {
        if ($installedReceipt) {
            $health = Get-InstalledFileHealth -Target $target -Receipt $installedReceipt
            if ($health.Healthy) {
                return ConvertTo-InstallerResult -State 'AlreadyInstalled' -Code 'AlreadyInstalled' -Message 'The installed program files are complete and verified.' -Version $sourceVersion -Target $target -HomePath $homePath -Files $payload.Files -RepairCommand (Get-RepairCommand $target)
            }
        }
        throw "The installed source is incomplete and cannot repair itself. $(Get-RepairCommand $target)"
    }
    if ($Update -and -not $installedReceipt) {
        throw "Codex Mode Switcher is not installed at $target. Use -Action Install."
    }
    if ($installedReceipt) {
        $installedVersion = [string]$installedReceipt.version
        if ($Update -and $sourceVersion -ne $installedVersion -and
            ([version]$sourceVersion -lt [version]$installedVersion) -and -not $Force) {
            throw "Source version $sourceVersion is older than installed version $installedVersion. Use -Force only after reviewing the downgrade."
        }
        $health = Get-InstalledFileHealth -Target $target -Receipt $installedReceipt
        if ($health.Modified.Count -and -not $Force) {
            throw ("Installed program files were modified: " + ($health.Modified -join ', ') + '. Use -Force to replace them after reviewing local changes.')
        }
        if (-not $Update -and $health.Healthy) {
            return ConvertTo-InstallerResult -State 'AlreadyInstalled' -Code 'AlreadyInstalled' -Message 'The installed program files are complete and verified. Use -Action Update to reinstall from this archive.' -Version $installedVersion -Target $target -HomePath $homePath -Files $payload.Files -Shims @($installedReceipt.shims) -RepairCommand (Get-RepairCommand $target)
        }
    } elseif ([IO.Directory]::Exists($target) -and @(Get-ChildItem -LiteralPath $target -Force).Count) {
        throw "Refusing to replace a non-empty directory not created by this installer: $target. Choose an empty or new install directory."
    }

    if ($DryRun -or -not $script:ShouldProcessApproved) {
        return ConvertTo-InstallerResult -State 'Planned' -Code 'Planned' -Message "$Action would install $sourceVersion to $target and leave CODEX_HOME user data unchanged." -Version $sourceVersion -Target $target -HomePath $homePath -Files $payload.Files -RepairCommand (Get-RepairCommand $target)
    }

    $parent = Split-Path -Path $target -Parent
    [void][IO.Directory]::CreateDirectory($parent)
    $leaf = Split-Path -Path $target -Leaf
    $staging = Join-Path $parent ('.' + $leaf + '.staging-' + [guid]::NewGuid().ToString('N'))
    $old = Join-Path $parent ('.' + $leaf + '.old-' + [guid]::NewGuid().ToString('N'))
    $movedOld = $false
    try {
        [void][IO.Directory]::CreateDirectory($staging)
        $files = Copy-Payload -Source $source -Target $staging
        $ownedManifest = Get-CodexModePayloadManifest -Root $staging -Version $sourceVersion
        Write-JsonFile -Path (Join-Path $staging 'release-manifest.json') -Value $ownedManifest
        if (-not ($files -contains 'release-manifest.json')) { $files += 'release-manifest.json' }
        $receipt = Format-InstallReceipt -Target $staging -Source $source -Version $sourceVersion
        Write-JsonFile -Path (Join-Path $staging 'install.json') -Value $receipt
        Invoke-ModuleImportCheck -Target $staging

        if ([IO.Directory]::Exists($target)) {
            Move-Item -LiteralPath $target -Destination $old
            $movedOld = $true
        }
        try {
            Move-Item -LiteralPath $staging -Destination $target
        } catch {
            if ($movedOld) { Move-Item -LiteralPath $old -Destination $target }
            throw
        }
        if ($movedOld) {
            try { Remove-Item -LiteralPath $old -Recurse -Force }
            catch { $script:Warnings.Add("Previous program files were preserved at $old because removal failed.") }
        }

        $targetReceipt = Get-InstallReceipt -Target $target
        $existingShims = if ($installedReceipt) { @($installedReceipt.shims) } else { @() }
        $shims = Install-LegacyEntry -Target $target -HomePath $homePath -ExistingShims $existingShims -DryRun:$DryRun
        $targetReceipt.shims = @($shims)
        Write-JsonFile -Path (Join-Path $target 'install.json') -Value $targetReceipt
        $state = if ($Update) { 'Updated' } else { 'Installed' }
        return ConvertTo-InstallerResult -State $state -Code $state -Message "Codex Mode Switcher $sourceVersion is installed and verified. CODEX_HOME configuration, credentials, sessions and backups were not modified." -Version $sourceVersion -Target $target -HomePath $homePath -Files $files -Shims @($shims) -RepairCommand (Get-RepairCommand $target) -Warnings @($script:Warnings)
    } finally {
        if ([IO.Directory]::Exists($staging)) { Remove-Item -LiteralPath $staging -Recurse -Force -ErrorAction SilentlyContinue }
        if ($movedOld -and [IO.Directory]::Exists($old) -and -not [IO.Directory]::Exists($target)) {
            Move-Item -LiteralPath $old -Destination $target
        }
    }
}

function Invoke-VerifyAction {
    $target = Resolve-InstallDirectory -Path $InstallDirectory
    $homePath = Resolve-CodexHome -Path $CodexHome
    $source = if (-not [string]::IsNullOrWhiteSpace($SourceDirectory)) {
        Resolve-FullDirectoryPath -Path $SourceDirectory -Description 'Source directory'
    } else {
        Resolve-FullDirectoryPath -Path (Split-Path -Path $PSScriptRoot -Parent) -Description 'Source directory'
    }
    Assert-TargetSafety -Target $target -HomePath $homePath -Source $source -Action 'Verify'
    if (-not [IO.Directory]::Exists($target)) {
        return ConvertTo-InstallerResult -State 'NotInstalled' -Code 'NotInstalled' -Message "No Codex Mode Switcher installation exists at $target." -Target $target -HomePath $homePath -RepairCommand (Get-RepairCommand $target)
    }
    $receipt = Get-InstallReceipt -Target $target
    if (-not $receipt) {
        return ConvertTo-InstallerResult -State 'Broken' -Code 'ReceiptMissing' -Message "The installation receipt is missing from $target. Reinstall from the complete release archive." -Target $target -HomePath $homePath -RepairCommand (Get-RepairCommand $target) -Warnings @($script:Warnings)
    }
    $health = Get-InstalledFileHealth -Target $target -Receipt $receipt
    foreach ($record in @($receipt.shims)) {
        if (-not $record.path) { continue }
        if (-not [IO.File]::Exists([string]$record.path)) { $script:Warnings.Add("Legacy entry shim is missing: $($record.path)") }
        elseif ((Get-CodexModeFileHash -Path ([string]$record.path)) -cne [string]$record.sha256) { $script:Warnings.Add("Legacy entry shim was modified: $($record.path)") }
        if ($record.original_exists -and (-not $record.backup_path -or -not [IO.File]::Exists([string]$record.backup_path))) {
            $script:Warnings.Add("Original legacy entry backup is missing for $($record.path)")
        }
    }
    $moduleError = $null
    try { Invoke-ModuleImportCheck -Target $target }
    catch { $moduleError = $_.Exception.Message }
    if ($health.Missing.Count -or $health.Modified.Count -or $moduleError) {
        $parts = [Collections.Generic.List[string]]::new()
        if ($health.Missing.Count) { $parts.Add('missing: ' + ($health.Missing -join ', ')) }
        if ($health.Modified.Count) { $parts.Add('modified: ' + ($health.Modified -join ', ')) }
        if ($moduleError) { $parts.Add($moduleError) }
        return ConvertTo-InstallerResult -State 'Broken' -Code 'FilesInvalid' -Message ("Installation verification failed ($($parts -join '; ')).") -Version ([string]$receipt.version) -Target $target -HomePath $homePath -Files @($receipt.files) -Shims @($receipt.shims) -RepairCommand (Get-RepairCommand $target) -Warnings @($script:Warnings)
    }
    return ConvertTo-InstallerResult -State 'Healthy' -Code 'Healthy' -Message 'Program files, module import and recorded entry shims are valid. CODEX_HOME user data was not inspected or changed.' -Version ([string]$receipt.version) -Target $target -HomePath $homePath -Files @($receipt.files) -Shims @($receipt.shims) -Warnings @($script:Warnings)
}

function Invoke-UninstallAction {
    $target = Resolve-InstallDirectory -Path $InstallDirectory
    $homePath = Resolve-CodexHome -Path $CodexHome
    $source = Resolve-FullDirectoryPath -Path (Split-Path -Path $PSScriptRoot -Parent) -Description 'Source directory'
    Assert-TargetSafety -Target $target -HomePath $homePath -Source $source -Action 'Uninstall'
    if (-not [IO.Directory]::Exists($target)) {
        return ConvertTo-InstallerResult -State 'NotInstalled' -Code 'NotInstalled' -Message "No Codex Mode Switcher installation exists at $target." -Target $target -HomePath $homePath
    }
    $receipt = Get-InstallReceipt -Target $target
    if (-not $receipt -and -not $Force) {
        throw "The installation receipt is missing from $target. Refusing to delete an unverified directory; use -Force after reviewing its contents."
    }
    if (-not $receipt -and $Force) {
        $userDataNames = @('config.toml', 'auth.json', 'sessions', 'archived_sessions', 'mode-switcher', 'deepseek-state.json', 'gpt-state.json', 'credentials', '.codex')
        foreach ($name in $userDataNames) {
            if (Test-Path -LiteralPath (Join-Path $target $name)) {
                throw "Refusing forced uninstall because $target contains Codex user data ($name). Run the uninstaller against the dedicated tool directory only."
            }
        }
    }
    if ($receipt) {
        $health = Get-InstalledFileHealth -Target $target -Receipt $receipt
        if ($health.Modified.Count -and -not $Force) {
            throw ("Refusing to remove modified program files: " + ($health.Modified -join ', ') + '. Use -Force after reviewing local changes.')
        }
    }
    if ($DryRun -or -not $script:ShouldProcessApproved) {
        return ConvertTo-InstallerResult -State 'Planned' -Code 'Planned' -Message "Uninstall would remove $target and recorded entry shims, restoring legacy entries when backups are valid. CODEX_HOME user data is not removed." -Version $(if ($receipt) { [string]$receipt.version }) -Target $target -HomePath $homePath -Files $(if ($receipt) { @($receipt.files) } else { @() }) -Shims $(if ($receipt) { @($receipt.shims) } else { @() })
    }

    $restore = if ($receipt) { Restore-LegacyEntry -Shims @($receipt.shims) } else { [pscustomobject]@{ Restored = @(); Removed = @() } }
    $parent = Split-Path -Path $target -Parent
    $leaf = Split-Path -Path $target -Leaf
    $trash = Join-Path $parent ('.' + $leaf + '.uninstall-' + [guid]::NewGuid().ToString('N'))
    Move-Item -LiteralPath $target -Destination $trash
    $leftover = $null
    try { Remove-Item -LiteralPath $trash -Recurse -Force }
    catch {
        $leftover = $trash
        $script:Warnings.Add("Program files were moved out of the install path but could not be fully deleted: $trash")
    }
    if ($receipt) {
        foreach ($record in @($receipt.shims)) {
            if ($record.backup_path) {
                $backupDirectory = Split-Path -Path ([string]$record.backup_path) -Parent
                if ($backupDirectory -and (Test-PathWithin -Child $backupDirectory -Parent (Get-InstallerStateDirectory))) {
                    Remove-Item -LiteralPath $backupDirectory -Recurse -Force -ErrorAction SilentlyContinue
                }
            }
        }
    }
    $stateDirectory = Get-InstallerStateDirectory
    foreach ($directory in @((Join-Path $stateDirectory 'legacy-backups'), $stateDirectory)) {
        if ([IO.Directory]::Exists($directory) -and -not @(Get-ChildItem -LiteralPath $directory -Force).Count) {
            Remove-Item -LiteralPath $directory -Force -ErrorAction SilentlyContinue
        }
    }
    $restoredText = if (@($restore.Restored).Count) { ' Restored legacy entries: ' + (@($restore.Restored) -join ', ') + '.' } else { '' }
    return ConvertTo-InstallerResult -State 'Uninstalled' -Code 'Uninstalled' -Message ('Program files were removed. CODEX_HOME configuration, credentials, sessions and user backups were preserved.' + $restoredText) -Version $(if ($receipt) { [string]$receipt.version }) -Target $target -HomePath $homePath -Shims @($restore.Restored) -Warnings @($script:Warnings) -LeftoverPath $leftover
}

try {
    $result = switch ($Action) {
        'Install' { Invoke-InstallAction }
        'Update' { Invoke-InstallAction -Update }
        'Verify' { Invoke-VerifyAction }
        'Uninstall' { Invoke-UninstallAction }
    }
    Write-InstallerResult -Result $result
    if ($result.State -in @('Failed', 'Broken', 'NotInstalled')) { exit 1 }
    exit 0
} catch {
    $message = $_.Exception.Message
    $target = try { Resolve-InstallDirectory -Path $InstallDirectory } catch { $null }
    $homePath = try { Resolve-CodexHome -Path $CodexHome } catch { $null }
    $result = ConvertTo-InstallerResult -State 'Failed' -Code 'InstallerError' -Message $message -Target $target -HomePath $homePath -RepairCommand $(if ($target) { Get-RepairCommand $target } else { $null }) -Warnings @($script:Warnings)
    Write-InstallerResult -Result $result
    exit 1
}
