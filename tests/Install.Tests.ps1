BeforeAll {
    $script:Root = Split-Path -Path $PSScriptRoot -Parent
    $script:Installer = Join-Path $script:Root 'scripts/Install-CodexMode.ps1'
    $script:Entry = Join-Path $script:Root 'codex-mode.ps1'
    $script:Pwsh = (Get-Command pwsh).Source

    function Invoke-CodexInstaller {
        param([string[]]$Arguments, [string]$InstallerPath = $script:Installer)
        $output = & $script:Pwsh -NoLogo -NoProfile -NonInteractive -File $InstallerPath @Arguments 2>&1
        $exitCode = $LASTEXITCODE
        $text = ($output | Out-String).Trim()
        $json = $null
        try { $json = $text | ConvertFrom-Json -AsHashtable -ErrorAction Stop } catch { $json = $null }
        [pscustomobject]@{ ExitCode = $exitCode; Text = $text; Json = $json }
    }

    function Get-TestCodexHome {
        $codexHome = Join-Path $TestDrive ([guid]::NewGuid().ToString('N'))
        New-Item -ItemType Directory -Path $codexHome | Out-Null
        [IO.File]::WriteAllText((Join-Path $codexHome 'config.toml'), "model = `"synthetic`"`nmodel_provider = `"custom`"`n")
        [IO.File]::WriteAllText((Join-Path $codexHome 'auth.json'), '{"synthetic":true}')
        New-Item -ItemType Directory -Path (Join-Path $codexHome 'sessions') | Out-Null
        [IO.File]::WriteAllText((Join-Path $codexHome 'sessions/session.json'), '{"synthetic":true}')
        New-Item -ItemType Directory -Path (Join-Path $codexHome 'mode-switcher/backups') -Force | Out-Null
        [IO.File]::WriteAllText((Join-Path $codexHome 'mode-switcher/deepseek-state.json'), '{"synthetic":true}')
        [IO.File]::WriteAllText((Join-Path $codexHome 'mode-switcher/backups/config.backup.toml'), 'backup')
        return $codexHome
    }

    function Get-ProtectedHash {
        param([string]$CodexHome)
        $paths = @(
            (Join-Path $CodexHome 'config.toml')
            (Join-Path $CodexHome 'auth.json')
            (Join-Path $CodexHome 'sessions/session.json')
            (Join-Path $CodexHome 'mode-switcher/deepseek-state.json')
            (Join-Path $CodexHome 'mode-switcher/backups/config.backup.toml')
        )
        $result = @{}
        foreach ($path in $paths) { $result[$path] = (Get-FileHash -LiteralPath $path -Algorithm SHA256).Hash }
        return $result
    }
}

Describe 'Entry-point repair guidance' {
    It 'reports missing module files without a raw Import-Module exception' {
        $broken = Join-Path $TestDrive 'broken'
        New-Item -ItemType Directory -Path $broken | Out-Null
        Copy-Item -LiteralPath $script:Entry -Destination (Join-Path $broken 'codex-mode.ps1')
        $output = & $script:Pwsh -NoLogo -NoProfile -NonInteractive -File (Join-Path $broken 'codex-mode.ps1') Status 2>&1
        $exitCode = $LASTEXITCODE
        $text = ($output | Out-String)
        $exitCode | Should -Be 2
        $text | Should -Match 'Codex Mode Switcher is incomplete'
        $text | Should -Match 'src/CodexMode\.psm1'
        $text | Should -Match 'install\.ps1 -Action Install'
        $text | Should -Not -Match 'Could not find a part of the path|Import-Module:'
    }
}

Describe 'Installer lifecycle' {
    It 'installs the complete payload and preserves CODEX_HOME configuration, credentials, sessions and backups' {
        $codexHome = Get-TestCodexHome
        $legacy = '# legacy v0.2.0 single-file entry'
        [IO.File]::WriteAllText((Join-Path $codexHome 'codex-mode.ps1'), $legacy)
        $before = Get-ProtectedHash -CodexHome $codexHome
        $target = Join-Path $TestDrive 'install-complete'

        $result = Invoke-CodexInstaller -Arguments @('-Action', 'Install', '-InstallDirectory', $target, '-CodexHome', $codexHome, '-Json')
        $result.ExitCode | Should -Be 0
        $result.Json.State | Should -Be 'Installed'
        foreach ($relative in @('codex-mode.ps1', 'codex-mode.cmd', 'CodexModeSwitcher.psd1',
            'src/CodexMode.psm1', 'src/Config.ps1', 'scripts/Invoke-Command.ps1',
            'install.ps1', 'install.json', 'release-manifest.json')) {
            Test-Path -LiteralPath (Join-Path $target $relative) | Should -BeTrue
        }
        $legacyText = [IO.File]::ReadAllText((Join-Path $codexHome 'codex-mode.ps1'))
        $legacyText | Should -Match 'Generated by Codex Mode Switcher installer'
        $legacyText | Should -Match ([regex]::Escape((Join-Path $target 'codex-mode.ps1')))
        $after = Get-ProtectedHash -CodexHome $codexHome
        foreach ($path in $before.Keys) { $after[$path] | Should -Be $before[$path] }
    }

    It 'updates in place, verifies, and uninstalls while restoring the legacy entry and preserving user data' {
        $codexHome = Get-TestCodexHome
        $legacy = '# legacy original entry'
        [IO.File]::WriteAllText((Join-Path $codexHome 'codex-mode.ps1'), $legacy)
        $before = Get-ProtectedHash -CodexHome $codexHome
        $target = Join-Path $TestDrive 'install-lifecycle'

        (Invoke-CodexInstaller -Arguments @('-Action', 'Install', '-InstallDirectory', $target, '-CodexHome', $codexHome, '-Json')).Json.State | Should -Be 'Installed'
        $verify = Invoke-CodexInstaller -Arguments @('-Action', 'Verify', '-InstallDirectory', $target, '-CodexHome', $codexHome, '-Json')
        $verify.ExitCode | Should -Be 0
        $verify.Json.State | Should -Be 'Healthy'

        $update = Invoke-CodexInstaller -Arguments @('-Action', 'Update', '-InstallDirectory', $target, '-CodexHome', $codexHome, '-Json')
        $update.ExitCode | Should -Be 0
        $update.Json.State | Should -Be 'Updated'

        $uninstall = Invoke-CodexInstaller -Arguments @('-Action', 'Uninstall', '-InstallDirectory', $target, '-CodexHome', $codexHome, '-Json')
        $uninstall.ExitCode | Should -Be 0
        $uninstall.Json.State | Should -Be 'Uninstalled'
        Test-Path -LiteralPath $target | Should -BeFalse
        [IO.File]::ReadAllText((Join-Path $codexHome 'codex-mode.ps1')) | Should -BeExactly $legacy
        $after = Get-ProtectedHash -CodexHome $codexHome
        foreach ($path in $before.Keys) { $after[$path] | Should -Be $before[$path] }
    }

    It 'reports a missing module and can uninstall the broken installation' {
        $codexHome = Get-TestCodexHome
        $target = Join-Path $TestDrive 'install-broken'
        (Invoke-CodexInstaller -Arguments @('-Action', 'Install', '-InstallDirectory', $target, '-CodexHome', $codexHome, '-Json')).Json.State | Should -Be 'Installed'
        [IO.File]::Delete((Join-Path $target 'src/CodexMode.psm1'))

        $verify = Invoke-CodexInstaller -Arguments @('-Action', 'Verify', '-InstallDirectory', $target, '-CodexHome', $codexHome, '-Json')
        $verify.ExitCode | Should -Be 1
        $verify.Json.State | Should -Be 'Broken'
        $verify.Json.Message | Should -Match 'missing: src/CodexMode\.psm1'
        $verify.Json.Message | Should -Not -Match 'The module to process'

        $uninstall = Invoke-CodexInstaller -Arguments @('-Action', 'Uninstall', '-InstallDirectory', $target, '-CodexHome', $codexHome, '-Json')
        $uninstall.ExitCode | Should -Be 0
        Test-Path -LiteralPath $target | Should -BeFalse
    }

    It 'can uninstall from the installed copy without leaving the program directory behind' {
        $codexHome = Get-TestCodexHome
        $target = Join-Path $TestDrive 'install-self-uninstall'
        (Invoke-CodexInstaller -Arguments @('-Action', 'Install', '-InstallDirectory', $target, '-CodexHome', $codexHome, '-Json')).Json.State | Should -Be 'Installed'
        $installedInstaller = Join-Path $target 'scripts/Install-CodexMode.ps1'
        $result = Invoke-CodexInstaller -InstallerPath $installedInstaller -Arguments @('-Action', 'Uninstall', '-InstallDirectory', $target, '-CodexHome', $codexHome, '-Json')
        $result.ExitCode | Should -Be 0
        $result.Json.State | Should -Be 'Uninstalled'
        Test-Path -LiteralPath $target | Should -BeFalse
    }

    It 'refuses to install from a partial source distribution' {
        $partial = Join-Path $TestDrive 'partial'
        New-Item -ItemType Directory -Path $partial | Out-Null
        Copy-Item -LiteralPath $script:Entry -Destination (Join-Path $partial 'codex-mode.ps1')
        $result = Invoke-CodexInstaller -Arguments @('-Action', 'Install', '-SourceDirectory', $partial, '-InstallDirectory', (Join-Path $TestDrive 'partial-target'), '-CodexHome', (Join-Path $TestDrive 'partial-home'), '-Json')
        $result.ExitCode | Should -Be 1
        $result.Json.Message | Should -Match 'Incomplete Codex Mode Switcher distribution'
        $result.Json.Message | Should -Match 'complete CodexModeSwitcher-\*\.zip'
    }

    It 'does not delete an unverified non-empty directory' {
        $target = Join-Path $TestDrive 'unverified-target'
        New-Item -ItemType Directory -Path $target | Out-Null
        $userFile = Join-Path $target 'user-file.txt'
        [IO.File]::WriteAllText($userFile, 'keep me')
        $result = Invoke-CodexInstaller -Arguments @('-Action', 'Uninstall', '-InstallDirectory', $target, '-CodexHome', (Join-Path $TestDrive 'unverified-home'), '-Json')
        $result.ExitCode | Should -Be 1
        $result.Json.Message | Should -Match 'installation receipt is missing'
        [IO.File]::ReadAllText($userFile) | Should -BeExactly 'keep me'
    }

    It 'honors DryRun without creating an install directory' {
        $codexHome = Get-TestCodexHome
        $target = Join-Path $TestDrive 'dry-run-target'
        $result = Invoke-CodexInstaller -Arguments @('-Action', 'Install', '-InstallDirectory', $target, '-CodexHome', $codexHome, '-DryRun', '-Json')
        $result.ExitCode | Should -Be 0
        $result.Json.State | Should -Be 'Planned'
        Test-Path -LiteralPath $target | Should -BeFalse
        Test-Path -LiteralPath (Join-Path $codexHome 'codex-mode.ps1') | Should -BeFalse
    }
}
